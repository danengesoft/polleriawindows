CREATE SCHEMA EXA_CLINICA;

CREATE TABLE EXA_CLINICA.CLINICAS (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUC           CHAR(11)      NOT NULL,
    RAZON_SOCIAL  VARCHAR(150) NOT NULL,
    TELEFONO      VARCHAR(20),
    ACTIVO        SMALLINT     DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_CLINICA_RUC UNIQUE (RUC),
    CONSTRAINT CK_CLINICA_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE EXA_CLINICA.CONSULTORIOS (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLINICA  BIGINT        NOT NULL,
    CODIGO        VARCHAR(10)  NOT NULL,
    TARIFA_HORA  NUMERIC(8,2)  NOT NULL,
    ESTADO        VARCHAR(20)  DEFAULT 'DISPONIBLE' NOT NULL,
    CONSTRAINT FK_CONSULTORIO_CLINICA FOREIGN KEY (ID_CLINICA)
        REFERENCES EXA_CLINICA.CLINICAS(ID),
    CONSTRAINT UQ_CONSULTORIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_CONSULTORIO_TARIFA CHECK (TARIFA_HORA > 0),
    CONSTRAINT CK_CONSULTORIO_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'OCUPADO', 'MANTENIMIENTO'))
);

CREATE TABLE EXA_CLINICA.ESPECIALIDADES (
    ID      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO  VARCHAR(10)  NOT NULL,
    NOMBRE  VARCHAR(100) NOT NULL,
    CONSTRAINT UQ_ESPECIALIDAD_CODIGO UNIQUE (CODIGO)
);

