WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE TABLE POLLERIA.PEDIDOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE_ID NUMBER(19,0) NOT NULL,
    FECHA TIMESTAMP(6) NOT NULL,
    TIPO_PEDIDO VARCHAR2(15 CHAR) NOT NULL,
    ESTADO VARCHAR2(20 CHAR) NOT NULL,
    METODO_PAGO VARCHAR2(15 CHAR) NOT NULL,
    ESTADO_PAGO VARCHAR2(15 CHAR) NOT NULL,
    DIRECCION_ENTREGA VARCHAR2(300 CHAR),
    REFERENCIA_ENTREGA VARCHAR2(300 CHAR),
    TOTAL NUMBER(19,2) NOT NULL,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT FK_PEDIDOS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES POLLERIA.CLIENTES(ID),
    CONSTRAINT CK_PEDIDOS_TIPO CHECK (TIPO_PEDIDO IN ('PRESENCIAL','RECOJO','DELIVERY')),
    CONSTRAINT CK_PEDIDOS_ESTADO CHECK (ESTADO IN ('PENDIENTE','CONFIRMADO','EN_PREPARACION','LISTO','DESPACHADO','ENTREGADO','CANCELADO')),
    CONSTRAINT CK_PEDIDOS_METODO CHECK (METODO_PAGO IN ('EFECTIVO','YAPE','PLIN','TARJETA')),
    CONSTRAINT CK_PEDIDOS_PAGO CHECK (ESTADO_PAGO IN ('PENDIENTE','PAGADO','ANULADO')),
    CONSTRAINT CK_PEDIDOS_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT CK_PEDIDOS_DIRECCION CHECK (TIPO_PEDIDO <> 'DELIVERY' OR (DIRECCION_ENTREGA IS NOT NULL AND REGEXP_LIKE(DIRECCION_ENTREGA,'[^[:space:]]')))
);
CREATE INDEX POLLERIA.IX_PEDIDOS_CLIENTE ON POLLERIA.PEDIDOS(CLIENTE_ID);
CREATE TABLE POLLERIA.DETALLE_PEDIDOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID NUMBER(19,0) NOT NULL,
    PRODUCTO_ID NUMBER(19,0) NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120 CHAR) NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    CANTIDAD NUMBER(10,0) NOT NULL,
    SUBTOTAL NUMBER(19,2) NOT NULL,
    CONSTRAINT PK_DETALLE_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT FK_DETALLE_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES POLLERIA.PEDIDOS(ID),
    CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES POLLERIA.PRODUCTOS(ID),
    CONSTRAINT CK_DETALLE_NOMBRE CHECK (REGEXP_LIKE(NOMBRE_PRODUCTO,'[^[:space:]]')),
    CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0 AND CANTIDAD <= 2147483647),
    CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL >= 0 AND SUBTOTAL = PRECIO_UNITARIO * CANTIDAD)
);
CREATE INDEX POLLERIA.IX_DETALLE_PEDIDO ON POLLERIA.DETALLE_PEDIDOS(PEDIDO_ID);
CREATE INDEX POLLERIA.IX_DETALLE_PRODUCTO ON POLLERIA.DETALLE_PEDIDOS(PRODUCTO_ID);
EXIT
