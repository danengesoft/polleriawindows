-- Ejecutar una sola vez en FREEPDB1; no altera Catálogo ni elimina datos.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE TABLE POLLERIA.CLIENTES (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRES VARCHAR2(100 CHAR) NOT NULL,
    APELLIDOS VARCHAR2(100 CHAR) NOT NULL,
    TELEFONO VARCHAR2(12 CHAR) NOT NULL,
    CORREO VARCHAR2(254 CHAR),
    DIRECCION_PRINCIPAL VARCHAR2(300 CHAR),
    REFERENCIA VARCHAR2(300 CHAR),
    ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID),
    CONSTRAINT CK_CLIENTES_NOMBRES CHECK (REGEXP_LIKE(NOMBRES, '[^[:space:]]')),
    CONSTRAINT CK_CLIENTES_APELLIDOS CHECK (REGEXP_LIKE(APELLIDOS, '[^[:space:]]')),
    CONSTRAINT CK_CLIENTES_TELEFONO CHECK (REGEXP_LIKE(TELEFONO, '^(\+51)?[0-9]{7,9}$')),
    CONSTRAINT CK_CLIENTES_ACTIVO CHECK (ACTIVO IN (0,1))
);
-- Oracle no indexa claves NULL: permite varios clientes sin correo.
-- La validación detallada del formato de correo corresponde a @Email en Java.
CREATE UNIQUE INDEX POLLERIA.UQ_CLIENTES_CORREO ON POLLERIA.CLIENTES (LOWER(TRIM(CORREO)));
EXIT
