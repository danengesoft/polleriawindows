-- Ejecutar una sola vez en FREEPDB1; no elimina ni reemplaza tablas existentes.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE TABLE POLLERIA.CATEGORIAS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID),
    CONSTRAINT CK_CATEGORIAS_NOMBRE CHECK (REGEXP_LIKE(NOMBRE, '[^[:space:]]')),
    CONSTRAINT CK_CATEGORIAS_ACTIVO CHECK (ACTIVO IN (0,1))
);
-- Unicidad ante concurrencia: ignora mayúsculas y espacios exteriores.
-- El servicio normaliza además los espacios interiores antes de guardar.
CREATE UNIQUE INDEX POLLERIA.UQ_CATEGORIAS_NOMBRE
    ON POLLERIA.CATEGORIAS (UPPER(TRIM(NOMBRE)));
CREATE TABLE POLLERIA.PRODUCTOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    PRECIO NUMBER(10,2) NOT NULL,
    DISPONIBLE NUMBER(1,0) DEFAULT 1 NOT NULL,
    CATEGORIA_ID NUMBER(19,0) NOT NULL,
    IMAGEN_URL VARCHAR2(1000 CHAR),
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCTOS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES POLLERIA.CATEGORIAS(ID),
    CONSTRAINT CK_PRODUCTOS_NOMBRE CHECK (REGEXP_LIKE(NOMBRE, '[^[:space:]]')),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CK_PRODUCTOS_DISPONIBLE CHECK (DISPONIBLE IN (0,1)),
    CONSTRAINT CK_PRODUCTOS_IMAGEN CHECK (IMAGEN_URL IS NULL OR REGEXP_LIKE(IMAGEN_URL, '^https?://[^[:space:]]+$', 'i'))
);
CREATE INDEX POLLERIA.IX_PRODUCTOS_CATEGORIA ON POLLERIA.PRODUCTOS(CATEGORIA_ID);
EXIT
