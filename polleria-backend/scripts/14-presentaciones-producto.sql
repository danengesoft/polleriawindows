CREATE TABLE POLLERIA.PRESENTACIONES_PRODUCTO (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 PRODUCTO_ID NUMBER(19,0) NOT NULL,
 NOMBRE VARCHAR2(60 CHAR) NOT NULL,
 PRECIO NUMBER(10,2) NOT NULL,
 DISPONIBLE NUMBER(1,0) DEFAULT 1 NOT NULL,
 ELIMINADO NUMBER(1,0) DEFAULT 0 NOT NULL,
 CONSTRAINT PK_PRESENTACIONES PRIMARY KEY(ID),
 CONSTRAINT FK_PRESENTACION_PRODUCTO FOREIGN KEY(PRODUCTO_ID) REFERENCES POLLERIA.PRODUCTOS(ID),
 CONSTRAINT CK_PRESENTACION_PRECIO CHECK(PRECIO>0),
 CONSTRAINT CK_PRESENTACION_NOMBRE CHECK(REGEXP_LIKE(NOMBRE,'[^[:space:]]')),
 CONSTRAINT CK_PRESENTACION_DISP CHECK(DISPONIBLE IN(0,1)),
 CONSTRAINT CK_PRESENTACION_ELIM CHECK(ELIMINADO IN(0,1))
);
CREATE INDEX POLLERIA.IX_PRESENTACION_PRODUCTO ON POLLERIA.PRESENTACIONES_PRODUCTO(PRODUCTO_ID);
CREATE UNIQUE INDEX POLLERIA.UQ_PRESENTACION_NOMBRE ON POLLERIA.PRESENTACIONES_PRODUCTO
 (CASE WHEN ELIMINADO=0 THEN PRODUCTO_ID END,CASE WHEN ELIMINADO=0 THEN UPPER(TRIM(NOMBRE)) END);
INSERT INTO POLLERIA.PRESENTACIONES_PRODUCTO(PRODUCTO_ID,NOMBRE,PRECIO,DISPONIBLE,ELIMINADO)
 SELECT ID,'Única',PRECIO,DISPONIBLE,ELIMINADO FROM POLLERIA.PRODUCTOS;
ALTER TABLE POLLERIA.DETALLE_PEDIDOS ADD (PRESENTACION_ID NUMBER(19,0), NOMBRE_PRESENTACION VARCHAR2(60 CHAR));
COMMIT;
