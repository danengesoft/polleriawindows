-- Esquema POLLERIA para PostgreSQL (estado final equivalente a los antiguos scripts
-- 01..14 de Oracle). Se ejecuta una sola vez, como el usuario dueño de la base.
-- Los booleanos se guardan como INTEGER 0/1 porque las entidades usan
-- NumericBooleanConverter (igual que con NUMBER(1) en Oracle).

CREATE SCHEMA polleria;

CREATE TABLE polleria.categorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(80)  NOT NULL,
    descripcion VARCHAR(500),
    activo      INTEGER      DEFAULT 1 NOT NULL,
    eliminado   INTEGER      DEFAULT 0 NOT NULL,
    CONSTRAINT pk_categorias PRIMARY KEY (id),
    CONSTRAINT ck_categorias_nombre CHECK (nombre ~ '\S'),
    CONSTRAINT ck_categorias_activo CHECK (activo IN (0, 1)),
    CONSTRAINT ck_cat_eliminado CHECK (eliminado IN (0, 1))
);
CREATE UNIQUE INDEX uq_cat_nombre_vigente ON polleria.categorias (UPPER(TRIM(nombre))) WHERE eliminado = 0;

CREATE TABLE polleria.productos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(120)  NOT NULL,
    descripcion  VARCHAR(500),
    precio       NUMERIC(10,2) NOT NULL,
    disponible   INTEGER       DEFAULT 1 NOT NULL,
    categoria_id BIGINT        NOT NULL,
    imagen_url   VARCHAR(1000),
    eliminado    INTEGER       DEFAULT 0 NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (id),
    CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES polleria.categorias(id),
    CONSTRAINT ck_productos_nombre CHECK (nombre ~ '\S'),
    CONSTRAINT ck_productos_precio CHECK (precio > 0),
    CONSTRAINT ck_productos_disponible CHECK (disponible IN (0, 1)),
    CONSTRAINT ck_productos_imagen CHECK (imagen_url IS NULL OR imagen_url ~* '^https?://\S+$'),
    CONSTRAINT ck_prod_eliminado CHECK (eliminado IN (0, 1))
);
CREATE INDEX ix_productos_categoria ON polleria.productos (categoria_id);

CREATE TABLE polleria.presentaciones_producto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    producto_id BIGINT        NOT NULL,
    nombre      VARCHAR(60)   NOT NULL,
    precio      NUMERIC(10,2) NOT NULL,
    disponible  INTEGER       DEFAULT 1 NOT NULL,
    eliminado   INTEGER       DEFAULT 0 NOT NULL,
    CONSTRAINT pk_presentaciones PRIMARY KEY (id),
    CONSTRAINT fk_presentacion_producto FOREIGN KEY (producto_id) REFERENCES polleria.productos(id),
    CONSTRAINT ck_presentacion_precio CHECK (precio > 0),
    CONSTRAINT ck_presentacion_nombre CHECK (nombre ~ '\S'),
    CONSTRAINT ck_presentacion_disp CHECK (disponible IN (0, 1)),
    CONSTRAINT ck_presentacion_elim CHECK (eliminado IN (0, 1))
);
CREATE INDEX ix_presentacion_producto ON polleria.presentaciones_producto (producto_id);
CREATE UNIQUE INDEX uq_presentacion_nombre ON polleria.presentaciones_producto (producto_id, UPPER(TRIM(nombre)))
    WHERE eliminado = 0;

CREATE TABLE polleria.web_sesiones (
    id         VARCHAR(36)  PRIMARY KEY,
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    expira     TIMESTAMP(6) NOT NULL,
    revocada   INTEGER      DEFAULT 0 NOT NULL CHECK (revocada IN (0, 1))
);

CREATE TABLE polleria.clientes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombres             VARCHAR(100) NOT NULL,
    apellidos           VARCHAR(100) NOT NULL,
    telefono            VARCHAR(12)  NOT NULL,
    correo              VARCHAR(254),
    direccion_principal VARCHAR(300),
    referencia          VARCHAR(300),
    activo              INTEGER      DEFAULT 1 NOT NULL,
    keycloak_sub        VARCHAR(255),
    web_sesion_id       VARCHAR(36),
    web_huella          VARCHAR(64),
    correo_contacto_web VARCHAR(254),
    CONSTRAINT pk_clientes PRIMARY KEY (id),
    CONSTRAINT ck_clientes_nombres CHECK (nombres ~ '\S'),
    CONSTRAINT ck_clientes_apellidos CHECK (apellidos ~ '\S'),
    CONSTRAINT ck_clientes_telefono CHECK (telefono ~ '^(\+51)?[0-9]{7,9}$'),
    CONSTRAINT ck_clientes_activo CHECK (activo IN (0, 1)),
    CONSTRAINT uk_clientes_keycloak_sub UNIQUE (keycloak_sub),
    CONSTRAINT fk_clientes_web FOREIGN KEY (web_sesion_id) REFERENCES polleria.web_sesiones(id),
    CONSTRAINT uk_clientes_web UNIQUE (web_sesion_id, web_huella),
    CONSTRAINT ck_clientes_web CHECK (web_sesion_id IS NULL
        OR (web_huella IS NOT NULL AND keycloak_sub IS NULL AND correo IS NULL))
);
CREATE UNIQUE INDEX uq_clientes_correo ON polleria.clientes (LOWER(TRIM(correo)));

CREATE TABLE polleria.mesas (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero    VARCHAR(20) NOT NULL UNIQUE,
    capacidad INTEGER     NOT NULL CHECK (capacidad > 0),
    estado    VARCHAR(15) DEFAULT 'DISPONIBLE' NOT NULL CHECK (estado IN ('DISPONIBLE', 'RESERVADA', 'OCUPADA'))
);

CREATE TABLE polleria.ocupaciones_mesa (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id          BIGINT    NOT NULL REFERENCES polleria.mesas(id),
    cliente_id       BIGINT    NOT NULL REFERENCES polleria.clientes(id),
    fecha_reserva    TIMESTAMP NOT NULL,
    fecha_llegada    TIMESTAMP,
    fecha_liberacion TIMESTAMP,
    liberada_por_sub VARCHAR(255),
    CONSTRAINT ck_ocupacion_fechas CHECK (
        (fecha_llegada IS NULL OR fecha_llegada >= fecha_reserva)
        AND (fecha_liberacion IS NULL OR (fecha_llegada IS NOT NULL AND fecha_liberacion >= fecha_llegada)))
);
CREATE UNIQUE INDEX uq_ocupacion_vigente ON polleria.ocupaciones_mesa (mesa_id) WHERE fecha_liberacion IS NULL;

CREATE TABLE polleria.pedidos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cliente_id         BIGINT        NOT NULL,
    fecha              TIMESTAMP(6)  NOT NULL,
    tipo_pedido        VARCHAR(15)   NOT NULL,
    estado             VARCHAR(20)   NOT NULL,
    metodo_pago        VARCHAR(15)   NOT NULL,
    estado_pago        VARCHAR(15)   NOT NULL,
    direccion_entrega  VARCHAR(300),
    referencia_entrega VARCHAR(300),
    total              NUMERIC(19,2) NOT NULL,
    flujo_version      INTEGER       DEFAULT 1 NOT NULL,
    ocupacion_mesa_id  BIGINT,
    creado_por_sub     VARCHAR(255),
    cobrado_por_sub    VARCHAR(255),
    fecha_pago         TIMESTAMP(6),
    CONSTRAINT pk_pedidos PRIMARY KEY (id),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES polleria.clientes(id),
    CONSTRAINT fk_pedidos_ocupacion FOREIGN KEY (ocupacion_mesa_id) REFERENCES polleria.ocupaciones_mesa(id),
    CONSTRAINT ck_pedidos_tipo CHECK (tipo_pedido IN ('MESA', 'PARA_LLEVAR', 'DELIVERY', 'PRESENCIAL', 'RECOJO')),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN ('PENDIENTE', 'LISTO', 'EN_CAMINO', 'ENTREGADO', 'CONFIRMADO',
        'EN_PREPARACION', 'DESPACHADO', 'CANCELADO')),
    CONSTRAINT ck_pedidos_metodo CHECK (metodo_pago IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA')),
    CONSTRAINT ck_pedidos_pago CHECK (estado_pago IN ('PENDIENTE', 'PAGADO', 'ANULADO')),
    CONSTRAINT ck_pedidos_total CHECK (total >= 0),
    CONSTRAINT ck_pedidos_direccion CHECK (tipo_pedido <> 'DELIVERY'
        OR (direccion_entrega IS NOT NULL AND direccion_entrega ~ '\S')),
    CONSTRAINT ck_pedidos_flujo CHECK (flujo_version IN (1, 2) AND (flujo_version = 1 OR (
        tipo_pedido IN ('MESA', 'PARA_LLEVAR', 'DELIVERY')
        AND estado IN ('PENDIENTE', 'LISTO', 'EN_CAMINO', 'ENTREGADO')
        AND estado_pago IN ('PENDIENTE', 'PAGADO')
        AND (estado <> 'ENTREGADO' OR estado_pago = 'PAGADO')
        AND (estado <> 'EN_CAMINO' OR tipo_pedido = 'DELIVERY')
        AND ((tipo_pedido = 'MESA' AND ocupacion_mesa_id IS NOT NULL)
             OR (tipo_pedido <> 'MESA' AND ocupacion_mesa_id IS NULL)))))
);
CREATE INDEX ix_pedidos_cliente ON polleria.pedidos (cliente_id);
CREATE INDEX ix_pedidos_cobro ON polleria.pedidos (cobrado_por_sub, fecha_pago);
CREATE INDEX ix_pedidos_ocupacion ON polleria.pedidos (ocupacion_mesa_id);

CREATE TABLE polleria.detalle_pedidos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pedido_id           BIGINT        NOT NULL,
    producto_id         BIGINT        NOT NULL,
    nombre_producto     VARCHAR(120)  NOT NULL,
    precio_unitario     NUMERIC(10,2) NOT NULL,
    cantidad            INTEGER       NOT NULL,
    subtotal            NUMERIC(19,2) NOT NULL,
    promocion_id        VARCHAR(36),
    precio_regular      NUMERIC(10,2),
    presentacion_id     BIGINT,
    nombre_presentacion VARCHAR(60),
    CONSTRAINT pk_detalle_pedidos PRIMARY KEY (id),
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (pedido_id) REFERENCES polleria.pedidos(id),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES polleria.productos(id),
    CONSTRAINT ck_detalle_nombre CHECK (nombre_producto ~ '\S'),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario > 0),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_subtotal CHECK (subtotal >= 0 AND subtotal = precio_unitario * cantidad),
    CONSTRAINT ck_det_precio_reg CHECK (precio_regular IS NULL OR precio_regular >= precio_unitario)
);
CREATE INDEX ix_detalle_pedido ON polleria.detalle_pedidos (pedido_id);
CREATE INDEX ix_detalle_producto ON polleria.detalle_pedidos (producto_id);

CREATE TABLE polleria.web_pedidos (
    pedido_id           BIGINT       PRIMARY KEY REFERENCES polleria.pedidos(id),
    sesion_id           VARCHAR(36)  NOT NULL REFERENCES polleria.web_sesiones(id),
    sesion_acceso_id    VARCHAR(36)  REFERENCES polleria.web_sesiones(id),
    clave_idempotencia  VARCHAR(36)  NOT NULL,
    huella_solicitud    VARCHAR(64)  NOT NULL,
    usuario_sub         VARCHAR(255),
    nombres             VARCHAR(100) NOT NULL,
    apellidos           VARCHAR(100) NOT NULL,
    telefono            VARCHAR(12)  NOT NULL,
    correo_contacto     VARCHAR(254),
    recuperacion_hash   VARCHAR(64),
    recuperacion_expira TIMESTAMP(6),
    CONSTRAINT uk_web_pedido_clave UNIQUE (clave_idempotencia)
);
CREATE INDEX ix_web_pedido_acceso ON polleria.web_pedidos (sesion_acceso_id);
